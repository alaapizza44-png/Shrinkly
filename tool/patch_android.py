#!/usr/bin/env python3
"""
Adapts the Android project generated by `flutter create` for Shrinkly.

Run from the repository root AFTER `flutter create --platforms=android ...`:

    python3 tool/patch_android.py

  * AndroidManifest.xml: permissions, app label and the AdMob application id
    (from env ADMOB_APP_ID, else Google's TEST id).
  * Raises minSdk to 24.
  * Wires release signing to android/key.properties (optional, written by CI from secrets).
  * Installs the launcher icons.
"""
import glob
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANDROID = os.path.join(ROOT, "android")
APP = os.path.join(ANDROID, "app")
MANIFEST = os.path.join(APP, "src", "main", "AndroidManifest.xml")
ICONS = os.path.join(ROOT, "tool", "icons")
TPL = os.path.join(ROOT, "tool", "android_templates")

TEST_APP_ID = "ca-app-pub-3940256099942544~3347511713"  # Google's sample AdMob app id
APP_LABEL = "Shorts Maker"
MIN_SDK = 24


def die(msg):
    print(f"[patch_android] ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def read(p):
    with open(p, "r", encoding="utf-8") as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


def find_package():
    hits = glob.glob(os.path.join(APP, "src", "main", "kotlin", "**", "MainActivity.kt"), recursive=True)
    if not hits:
        hits = glob.glob(os.path.join(APP, "src", "main", "java", "**", "MainActivity.*"), recursive=True)
    if not hits:
        die("MainActivity not found - did `flutter create` run?")
    m = re.search(r"^\s*package\s+([\w.]+)", read(hits[0]), re.M)
    if not m:
        die(f"could not read package name from {hits[0]}")
    return m.group(1), hits[0]


def write_kotlin():
    """Replaces MainActivity with ours (adds the video info / thumbnail channel)."""
    pkg, main_path = find_package()
    write(main_path, read(os.path.join(TPL, "MainActivity.kt.tpl")).replace("__PKG__", pkg))
    # Second Kotlin file: the GPU sharpen filter, next to MainActivity.
    write(os.path.join(os.path.dirname(main_path), "SharpenEffect.kt"),
          read(os.path.join(TPL, "SharpenEffect.kt.tpl")).replace("__PKG__", pkg))
    write(os.path.join(os.path.dirname(main_path), "BlurFitEffect.kt"),
          read(os.path.join(TPL, "BlurFitEffect.kt.tpl")).replace("__PKG__", pkg))
    print(f"[patch_android] MainActivity + effects written for package {pkg}")


MEDIA3 = "1.5.1"


def patch_dependencies():
    """Adds the Media3 (Transformer) libraries used by the Shorts engine."""
    for name in ("build.gradle.kts", "build.gradle"):
        p = os.path.join(APP, name)
        if not os.path.exists(p):
            continue
        s = read(p)
        if "media3-transformer" in s:
            print("[patch_android] media3 dependencies already present")
            return
        kts = name.endswith(".kts")
        if kts:
            libs = "".join(f'    implementation("androidx.media3:{m}:{MEDIA3}")\n'
                           for m in ("media3-transformer", "media3-effect", "media3-common"))
        else:
            libs = "".join(f"    implementation 'androidx.media3:{m}:{MEDIA3}'\n"
                           for m in ("media3-transformer", "media3-effect", "media3-common"))
        m = re.search(r"^dependencies\s*\{\n", s, re.M)
        if m:
            s = s[:m.end()] + libs + s[m.end():]
        else:
            s = s.rstrip() + "\n\ndependencies {\n" + libs + "}\n"
        # The video preview plugin also ships Media3; every module must have the same version
        # or export fails at run time ("Failed resolution of ... LogSessionId").
        if kts:
            s += ("\nconfigurations.all {\n    resolutionStrategy.eachDependency {\n"
                  f"        if (requested.group == \"androidx.media3\") {{ useVersion(\"{MEDIA3}\") }}\n"
                  "    }\n}\n")
        else:
            s += ("\nconfigurations.all {\n    resolutionStrategy.eachDependency { d ->\n"
                  f"        if (d.requested.group == 'androidx.media3') {{ d.useVersion '{MEDIA3}' }}\n"
                  "    }\n}\n")
        write(p, s)
        print("[patch_android] media3 dependencies added to", name)
        return
    die("app build.gradle(.kts) not found")


def patch_manifest():
    if not os.path.exists(MANIFEST):
        die("AndroidManifest.xml not found")
    s = read(MANIFEST)
    if "shrinkly-patched" in s:
        print("[patch_android] manifest already patched")
        return

    app_id = (os.environ.get("ADMOB_APP_ID") or "").strip() or TEST_APP_ID
    if app_id == TEST_APP_ID:
        print("[patch_android] ADMOB_APP_ID not set -> using Google TEST app id (no real ad revenue)")
    if not re.fullmatch(r"ca-app-pub-\d{16}~\d{10}", app_id):
        die(f"ADMOB_APP_ID looks wrong: {app_id!r} (expected ca-app-pub-XXXXXXXXXXXXXXXX~YYYYYYYYYY)")

    perms = """
    <!-- shrinkly-patched -->
    <uses-permission android:name="android.permission.INTERNET"/>
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE"/>
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS"/>
    <uses-permission android:name="android.permission.WAKE_LOCK"/>
    <uses-permission android:name="android.permission.WRITE_EXTERNAL_STORAGE" android:maxSdkVersion="28"/>
"""
    s, n = re.subn(r"(<manifest\b[^>]*>)", lambda m: m.group(1) + perms, s, count=1)
    if n != 1:
        die("could not find <manifest> tag")

    m = re.search(r"<application\b[^>]*>", s, re.S)
    if not m:
        die("could not find <application> tag")
    tag = m.group(0)
    new_tag = re.sub(r'android:label="[^"]*"', f'android:label="{APP_LABEL}"', tag, count=1)
    if new_tag == tag and "android:label" not in tag:
        new_tag = tag.replace("<application", f'<application android:label="{APP_LABEL}"', 1)
    s = s.replace(tag, new_tag, 1)

    # One activity instance: tapping the progress notification returns to the running app.
    if 'android:launchMode="singleTop"' in s:
        s = s.replace('android:launchMode="singleTop"', 'android:launchMode="singleTask"', 1)
    elif "android:launchMode=" not in s:
        s = s.replace("<activity", '<activity android:launchMode="singleTask"', 1)

    extra = f"""
        <meta-data
            android:name="com.google.android.gms.ads.APPLICATION_ID"
            android:value="{app_id}"/>
    """
    if "</application>" not in s:
        die("could not find </application>")
    s = s.replace("</application>", extra + "</application>", 1)
    write(MANIFEST, s)
    print("[patch_android] manifest patched")


def patch_min_sdk():
    done = False
    for name, kts in (("build.gradle.kts", True), ("build.gradle", False)):
        p = os.path.join(APP, name)
        if not os.path.exists(p):
            continue
        s = read(p)
        pat = re.compile(r"minSdk(?:Version)?\s*=?\s*flutter\.minSdkVersion")
        if pat.search(s):
            s = pat.sub(f"minSdk = {MIN_SDK}" if kts else f"minSdkVersion {MIN_SDK}", s, count=1)
            write(p, s)
            done = True
        else:
            m = re.search(r"minSdk(?:Version)?\s*=?\s*(\d+)", s)
            if m and int(m.group(1)) < MIN_SDK:
                s = s.replace(m.group(0), f"minSdk = {MIN_SDK}" if kts else f"minSdkVersion {MIN_SDK}", 1)
                write(p, s)
                done = True
            elif m:
                done = True
    if not done:
        print("[patch_android] WARNING: could not adjust minSdk; relying on Flutter's default", file=sys.stderr)
    else:
        print(f"[patch_android] minSdk set to {MIN_SDK}")


def patch_signing():
    """Release signing from android/key.properties (written by CI from secrets).
    Without key.properties the build falls back to the debug key, so it still works."""
    for name, kts in (("build.gradle.kts", True), ("build.gradle", False)):
        p = os.path.join(APP, name)
        if not os.path.exists(p):
            continue
        s = read(p)
        if "keystoreProps" in s:
            print("[patch_android] signing already patched")
            return
        if kts:
            header = "import java.util.Properties\nimport java.io.FileInputStream\n\n"
            cfg = ("val keystoreProps = Properties().apply {\n"
                   "    val f = rootProject.file(\"key.properties\")\n"
                   "    if (f.exists()) load(FileInputStream(f))\n}\n\n"
                   "android {\n    signingConfigs {\n        create(\"release\") {\n"
                   "            if (keystoreProps.containsKey(\"storeFile\")) {\n"
                   "                storeFile = file(keystoreProps.getProperty(\"storeFile\"))\n"
                   "                storePassword = keystoreProps.getProperty(\"storePassword\")\n"
                   "                keyAlias = keystoreProps.getProperty(\"keyAlias\")\n"
                   "                keyPassword = keystoreProps.getProperty(\"keyPassword\")\n"
                   "            }\n        }\n    }\n")
            use = ('signingConfig = if (keystoreProps.containsKey("storeFile")) '
                   'signingConfigs.getByName("release") else signingConfigs.getByName("debug")')
            dbg = re.compile(r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)')
        else:
            header = ""
            cfg = ("def keystoreProps = new Properties()\n"
                   "def keystoreFile = rootProject.file('key.properties')\n"
                   "if (keystoreFile.exists()) keystoreProps.load(new FileInputStream(keystoreFile))\n\n"
                   "android {\n    signingConfigs {\n        release {\n"
                   "            if (keystoreProps.containsKey('storeFile')) {\n"
                   "                storeFile file(keystoreProps['storeFile'])\n"
                   "                storePassword keystoreProps['storePassword']\n"
                   "                keyAlias keystoreProps['keyAlias']\n"
                   "                keyPassword keystoreProps['keyPassword']\n"
                   "            }\n        }\n    }\n")
            use = ("signingConfig keystoreProps.containsKey('storeFile') ? "
                   "signingConfigs.release : signingConfigs.debug")
            dbg = re.compile(r'signingConfig\s+signingConfigs\.debug')
        if not dbg.search(s) or not re.search(r"^android\s*\{", s, re.M):
            print("[patch_android] WARNING: signing hook not found; release uses the debug key", file=sys.stderr)
            return
        s = dbg.sub(lambda m: use, s, count=1)
        s = re.sub(r"^android\s*\{\n", lambda m: cfg, s, count=1, flags=re.M)
        s = header + s
        write(p, s)
        print("[patch_android] release signing wired to key.properties")
        return


def install_icons():
    res = os.path.join(APP, "src", "main", "res")
    if not os.path.isdir(ICONS):
        die("tool/icons missing")
    for d in sorted(os.listdir(ICONS)):
        src = os.path.join(ICONS, d)
        if os.path.isdir(src) and d.startswith("mipmap-"):
            dst = os.path.join(res, d)
            os.makedirs(dst, exist_ok=True)
            for f in os.listdir(src):
                shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
    write(
        os.path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"),
        """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
""",
    )
    write(
        os.path.join(res, "values", "ic_launcher_background.xml"),
        """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#7C3AED</color>
</resources>
""",
    )
    print("[patch_android] launcher icons installed")


def main():
    if not os.path.isdir(ANDROID):
        die("android/ folder not found. Run `flutter create --platforms=android .` first.")
    patch_manifest()
    write_kotlin()
    patch_min_sdk()
    patch_dependencies()
    patch_signing()
    install_icons()
    print("[patch_android] done")


if __name__ == "__main__":
    main()
